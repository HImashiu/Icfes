-- M1 + M2: schools, profiles, courses, rosters, assignments, attempts.
-- Run in the Supabase SQL editor (or `supabase db push`). Safe to read: contains no exam content.
-- Question content is NOT stored here; the app database only holds exam slugs, question keys and responses.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- tables

create table public.schools (
  id           uuid primary key default gen_random_uuid(),
  name         text not null,
  -- email domains that may join (e.g. {'colegio.edu.co'}); lower case, no @
  domains      text[] not null check (cardinality(domains) > 0),
  -- teachers enter this code at first sign-in; the school admin shares it
  teacher_code text not null default encode(gen_random_bytes(5), 'hex'),
  status       text not null default 'active' check (status in ('active', 'suspended')),
  created_at   timestamptz not null default now()
);

create table public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  school_id  uuid not null references public.schools (id),
  role       text not null default 'student' check (role in ('student', 'teacher', 'school_admin')),
  full_name  text not null default '',
  email      text not null,
  created_at timestamptz not null default now()
);
create index profiles_school_idx on public.profiles (school_id);

create table public.courses (
  id         uuid primary key default gen_random_uuid(),
  school_id  uuid not null references public.schools (id),
  name       text not null,
  grade      text,
  year       int not null default extract(year from now())::int,
  created_by uuid not null references public.profiles (id),
  created_at timestamptz not null default now()
);
create index courses_school_idx on public.courses (school_id);

-- A roster row exists before the person signs in (profile_id null, matched by email at first sign-in).
create table public.course_members (
  id         uuid primary key default gen_random_uuid(),
  course_id  uuid not null references public.courses (id) on delete cascade,
  profile_id uuid references public.profiles (id) on delete cascade,
  email      text not null,
  full_name  text not null default '',
  role       text not null default 'student' check (role in ('student', 'teacher')),
  created_at timestamptz not null default now(),
  unique (course_id, email)
);
create index course_members_profile_idx on public.course_members (profile_id);

create table public.assignments (
  id             uuid primary key default gen_random_uuid(),
  course_id      uuid not null references public.courses (id) on delete cascade,
  created_by     uuid not null references public.profiles (id),
  kind           text not null check (kind in ('task', 'exam', 'homework')),
  title          text not null,
  exam_slug      text not null,
  -- 'all' or the name of one area
  scope          text not null default 'all',
  -- null means every question of the scope; otherwise the question keys, in order
  question_keys  text[],
  opens_at       timestamptz not null default now(),
  due_at         timestamptz,
  time_limit_min int check (time_limit_min is null or time_limit_min between 1 and 600),
  reveal_policy  text not null default 'after_submit' check (reveal_policy in ('after_submit', 'after_close', 'never')),
  status         text not null default 'active' check (status in ('draft', 'active', 'closed')),
  created_at     timestamptz not null default now()
);
create index assignments_course_idx on public.assignments (course_id);

create table public.attempts (
  id            uuid primary key default gen_random_uuid(),
  profile_id    uuid not null references public.profiles (id) on delete cascade,
  assignment_id uuid references public.assignments (id) on delete set null,
  -- generated by the browser so a retried upload does not create a duplicate
  client_id     text not null,
  exam_slug     text not null,
  scope         text not null default 'all',
  mode          text not null check (mode in ('practice', 'timed')),
  started_at    timestamptz not null,
  submitted_at  timestamptz,
  duration_sec  int,
  -- { "12": "B", ... }  and  { "12": 41, ... } seconds spent per question when known
  answers       jsonb not null default '{}'::jsonb,
  times         jsonb not null default '{}'::jsonb,
  -- computed in the browser against the PRELIMINARY key: { correct, answered, total, perArea: [...] }
  score         jsonb,
  key_status    text not null default 'preliminary',
  device        text,
  created_at    timestamptz not null default now(),
  unique (profile_id, client_id)
);
create index attempts_assignment_idx on public.attempts (assignment_id);

-- ---------------------------------------------------------------- helpers (security definer: they bypass RLS to avoid recursion)

create or replace function public.my_school() returns uuid
language sql stable security definer set search_path = public as $$
  select school_id from profiles where id = auth.uid()
$$;

create or replace function public.my_role() returns text
language sql stable security definer set search_path = public as $$
  select role from profiles where id = auth.uid()
$$;

create or replace function public.is_course_teacher(p_course uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from course_members
    where course_id = p_course and profile_id = auth.uid() and role = 'teacher'
  ) or exists (
    select 1 from courses c join profiles p on p.id = auth.uid()
    where c.id = p_course and c.school_id = p.school_id and p.role = 'school_admin'
  )
$$;

create or replace function public.is_course_member(p_course uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from course_members where course_id = p_course and profile_id = auth.uid())
$$;

-- ---------------------------------------------------------------- first sign-in

-- Called by the browser right after Google/Microsoft sign-in. The role is never taken from the token:
-- a person becomes a teacher only by presenting the school's teacher code.
-- Raises 'school_not_found' when the email domain belongs to no active school.
create or replace function public.claim_profile(p_teacher_code text default null, p_full_name text default null)
returns public.profiles
language plpgsql security definer set search_path = public as $$
declare
  v_uid   uuid := auth.uid();
  v_email text := lower(coalesce(auth.jwt() ->> 'email', ''));
  v_domain text := split_part(v_email, '@', 2);
  v_school schools;
  v_role  text := 'student';
  v_profile profiles;
begin
  if v_uid is null then raise exception 'not_signed_in'; end if;

  select * into v_profile from profiles where id = v_uid;
  if found then return v_profile; end if;

  select * into v_school from schools
   where status = 'active' and v_domain = any (domains) limit 1;
  if not found then raise exception 'school_not_found'; end if;

  if p_teacher_code is not null and length(trim(p_teacher_code)) > 0 then
    if lower(trim(p_teacher_code)) <> lower(v_school.teacher_code) then
      raise exception 'bad_teacher_code';
    end if;
    v_role := 'teacher';
  end if;

  insert into profiles (id, school_id, role, full_name, email)
  values (v_uid, v_school.id, v_role,
          coalesce(nullif(trim(p_full_name), ''), auth.jwt() -> 'user_metadata' ->> 'full_name', v_email),
          v_email)
  returning * into v_profile;

  -- Link any roster rows that were created for this email before the person signed in.
  update course_members set profile_id = v_uid, full_name = case when full_name = '' then v_profile.full_name else full_name end
   where profile_id is null and lower(email) = v_email;

  return v_profile;
end $$;

-- Keep roster rows linked when a teacher adds someone who already has a profile.
create or replace function public.link_member_profile() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.profile_id is null then
    select id into new.profile_id from profiles where lower(email) = lower(new.email) limit 1;
  end if;
  return new;
end $$;
create trigger course_members_link before insert on public.course_members
  for each row execute function public.link_member_profile();

-- The creator of a course is its first teacher.
create or replace function public.add_course_creator() returns trigger
language plpgsql security definer set search_path = public as $$
declare v_email text; v_name text;
begin
  select email, full_name into v_email, v_name from profiles where id = new.created_by;
  insert into course_members (course_id, profile_id, email, full_name, role)
  values (new.id, new.created_by, v_email, v_name, 'teacher');
  return new;
end $$;
create trigger courses_creator after insert on public.courses
  for each row execute function public.add_course_creator();

-- ---------------------------------------------------------------- row-level security

alter table public.schools        enable row level security;
alter table public.profiles       enable row level security;
alter table public.courses        enable row level security;
alter table public.course_members enable row level security;
alter table public.assignments    enable row level security;
alter table public.attempts       enable row level security;

-- schools: you see your own school (never the teacher_code unless you are staff: see view below)
create policy schools_select on public.schools for select
  using (id = public.my_school());

-- profiles: you see yourself; staff see the profiles of their school (students do not see each other: minors)
create policy profiles_select on public.profiles for select
  using (id = auth.uid() or (school_id = public.my_school() and public.my_role() in ('teacher', 'school_admin')));
create policy profiles_update_self on public.profiles for update
  using (id = auth.uid()) with check (id = auth.uid() and role = (select role from public.profiles where id = auth.uid())
                                       and school_id = (select school_id from public.profiles where id = auth.uid()));

-- courses
create policy courses_select on public.courses for select
  using (public.is_course_member(id) or public.is_course_teacher(id));
create policy courses_insert on public.courses for insert
  with check (created_by = auth.uid() and school_id = public.my_school() and public.my_role() in ('teacher', 'school_admin'));
create policy courses_update on public.courses for update
  using (public.is_course_teacher(id)) with check (public.is_course_teacher(id));
create policy courses_delete on public.courses for delete
  using (public.is_course_teacher(id));

-- course members: a student sees only their own row; teachers see and edit the whole roster of their courses
create policy members_select on public.course_members for select
  using (profile_id = auth.uid() or public.is_course_teacher(course_id));
create policy members_insert on public.course_members for insert
  with check (public.is_course_teacher(course_id));
create policy members_update on public.course_members for update
  using (public.is_course_teacher(course_id)) with check (public.is_course_teacher(course_id));
create policy members_delete on public.course_members for delete
  using (public.is_course_teacher(course_id));

-- assignments: students see active ones of their courses; teachers manage theirs
create policy assignments_select on public.assignments for select
  using (public.is_course_teacher(course_id) or (public.is_course_member(course_id) and status <> 'draft'));
create policy assignments_insert on public.assignments for insert
  with check (created_by = auth.uid() and public.is_course_teacher(course_id));
create policy assignments_update on public.assignments for update
  using (public.is_course_teacher(course_id)) with check (public.is_course_teacher(course_id));
create policy assignments_delete on public.assignments for delete
  using (public.is_course_teacher(course_id));

-- attempts: a student writes and reads their own; teachers read the attempts of their courses' assignments
create policy attempts_select on public.attempts for select
  using (profile_id = auth.uid()
         or (assignment_id is not null and exists (
               select 1 from public.assignments a where a.id = attempts.assignment_id and public.is_course_teacher(a.course_id))));
create policy attempts_insert on public.attempts for insert
  with check (profile_id = auth.uid()
              and (assignment_id is null or exists (
                     select 1 from public.assignments a
                     where a.id = assignment_id and public.is_course_member(a.course_id) and a.status = 'active')));
create policy attempts_update on public.attempts for update
  using (profile_id = auth.uid() and submitted_at is null)
  with check (profile_id = auth.uid());

-- Staff read the join code through this function only; students cannot.
create or replace function public.school_teacher_code() returns text
language sql stable security definer set search_path = public as $$
  select teacher_code from schools where id = public.my_school() and public.my_role() = 'school_admin'
$$;
revoke all on function public.school_teacher_code() from public, anon;
grant execute on function public.school_teacher_code() to authenticated;
revoke all on function public.claim_profile(text, text) from public, anon;
grant execute on function public.claim_profile(text, text) to authenticated;

-- schools.teacher_code must not leak through the schools_select policy.
revoke select on public.schools from authenticated;
grant select (id, name, domains, status, created_at) on public.schools to authenticated;
